"""Bake the two HUD typefaces and their proportional advances; see assets/README.md."""
import argparse
import math
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
EM, CELL, COLUMNS = 40, 64, 16
PEN_X, BASELINE = 7, 46
EXTRA = "—«»№•…←→↑↓×°·★–−"
CHARS = [chr(c) for c in range(32, 127)] + ["?"]
CHARS += [chr(c) for c in range(0x410, 0x450)] + list("Ёё" + EXTRA)
ROWS = (len(CHARS) + COLUMNS - 1) // COLUMNS


def symbol(draw, x, y, ch):
    """The source fonts omit the five HUD navigation marks."""
    cx, cy = x + 15, y - 14
    if ch == "★":
        points = []
        for i in range(10):
            a = math.pi * (i / 5 - .5)
            r = 15 if i % 2 == 0 else 6.3
            points.append((cx + r * math.cos(a), cy + r * math.sin(a)))
        draw.polygon(points, fill="white")
    else:
        dx, dy = {"→": (1, 0), "←": (-1, 0), "↓": (0, 1), "↑": (0, -1)}[ch]
        def point(a, b):
            return cx + a * dx - b * dy, cy + a * dy + b * dx
        draw.line([point(-13, 0), point(12, 0)], fill="white", width=3)
        draw.line([point(4, -8), point(12, 0), point(4, 8)], fill="white", width=3)
    return 32.0


def bake(body, heading):
    atlas = Image.new("RGBA", (COLUMNS * CELL, 2 * ROWS * CELL))
    draw = ImageDraw.Draw(atlas)
    header = [
        "// Generated by tools/make_combat_font.py. Advances are in 1/64 source pixels.",
        "#pragma once", "namespace uiFont {",
        f"inline constexpr int em={EM}, cell={CELL}, columns={COLUMNS}, rows={ROWS};",
        f"inline constexpr int penX={PEN_X}, baseline={BASELINE};",
        "inline constexpr unsigned extra[]={" + ", ".join(hex(ord(c)) for c in EXTRA) + "};",
        f"inline constexpr unsigned short advances[2][{len(CHARS)}]={{"
    ]
    for face, source in enumerate((body, heading)):
        font = ImageFont.truetype(str(source), EM)
        advances = []
        for i, ch in enumerate(CHARS):
            x = i % COLUMNS * CELL + PEN_X
            y = (i // COLUMNS + face * ROWS) * CELL + BASELINE
            if ch in "★←→↑↓":
                width = symbol(draw, x, y, ch)
            else:
                l, t, r, b = font.getbbox(ch, anchor="ls")
                assert -PEN_X <= l and r < CELL - PEN_X and -BASELINE <= t and b < CELL - BASELINE
                draw.text((x, y), ch, font=font, anchor="ls", fill="white")
                width = font.getlength(ch)
            advances.append(round(width * 64))
        header.append("    {")
        for i in range(0, len(advances), COLUMNS):
            header.append("        " + ", ".join(map(str, advances[i:i+COLUMNS])) + ",")
        header.append("    },")
    header += ["};", "}", ""]
    (ROOT / "src/ui_font_metrics.hpp").write_text("\n".join(header), encoding="utf-8")
    atlas.save(ROOT / "assets/combat-font.png", optimize=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("body", type=Path, help="PT_Sans-Web-Regular.ttf")
    parser.add_argument("heading", type=Path, help="PT_Serif-Web-Regular.ttf")
    args = parser.parse_args()
    bake(args.body, args.heading)
